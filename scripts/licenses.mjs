/**
 * Dependency license policy.
 *
 *   node scripts/licenses.mjs --check   fail on disallowed licenses, or if
 *                                       THIRD_PARTY_LICENSES.md is outdated
 *   node scripts/licenses.mjs --write   regenerate THIRD_PARTY_LICENSES.md
 *
 * Production dependencies (shipped in the editor, player or exported
 * courses) must use a permissive license. Development tools are only
 * reported: they are not distributed and do not affect the output.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ALLOWED = new Set([
  'MIT',
  'ISC',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'BlueOak-1.0.0',
]);
/** Dev-only tools under other licenses that were reviewed and accepted. */
export const DEV_EXCEPTIONS = new Map([
  ['lightningcss', 'MPL-2.0, CSS tooling used by Vite at build time; not shipped'],
]);

const root = fileURLToPath(new URL('..', import.meta.url));
const outFile = join(root, 'THIRD_PARTY_LICENSES.md');

function listLicenses(kind) {
  const json = execFileSync('pnpm', ['licenses', 'list', `--${kind}`, '--json'], {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  const byLicense = JSON.parse(json || '{}');
  const packages = [];
  for (const [license, entries] of Object.entries(byLicense)) {
    for (const entry of entries) packages.push({ ...entry, license });
  }
  return packages.sort((a, b) => a.name.localeCompare(b.name));
}

function licenseText(pkgPath) {
  if (!pkgPath || !existsSync(pkgPath)) return null;
  const file = readdirSync(pkgPath).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  return file ? readFileSync(join(pkgPath, file), 'utf8').replace(/\r\n?/g, '\n').trim() : null;
}

/** Accepts SPDX expressions like "(MIT OR Apache-2.0)" if any option is allowed. */
export function isAllowed(expression) {
  const options = expression.replace(/[()]/g, '').split(/\s+OR\s+/);
  return options.some((option) =>
    option.split(/\s+AND\s+/).every((part) => ALLOWED.has(part.trim())),
  );
}

export function renderMarkdown(packages) {
  const lines = [
    '# Third-party licenses',
    '',
    'Production dependencies of Clipcourse. Generated by `pnpm licenses:write`; do not edit by hand.',
    '',
    'The player runtime (`@clipcourse/player`) has no third-party runtime dependencies, so exported',
    'courses contain no third-party code.',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...packages.map((p) => `| ${p.name} | ${p.versions.join(', ')} | ${p.license} |`),
    '',
  ];
  for (const p of packages) {
    lines.push(`## ${p.name} ${p.versions.join(', ')}`, '');
    lines.push(`License: ${p.license}${p.homepage ? `  \nHomepage: ${p.homepage}` : ''}`, '');
    const text = licenseText(p.paths?.[0]);
    lines.push(
      '```text',
      text ?? `(no license file shipped; license declared as ${p.license})`,
      '```',
      '',
    );
  }
  return lines.join('\n');
}

function main() {
  const mode = process.argv[2];
  if (mode !== '--check' && mode !== '--write') {
    console.error('usage: licenses.mjs --check | --write');
    process.exit(2);
  }

  const prod = listLicenses('prod');
  const dev = listLicenses('dev');
  let failed = false;

  for (const p of prod) {
    if (!isAllowed(p.license)) {
      console.error(
        `DISALLOWED production dependency: ${p.name}@${p.versions.join(',')} (${p.license})`,
      );
      failed = true;
    }
  }
  for (const p of dev) {
    if (isAllowed(p.license)) continue;
    const exception = DEV_EXCEPTIONS.get(p.name);
    if (exception) {
      console.log(`note: dev dependency ${p.name} (${exception})`);
    } else {
      console.error(`UNREVIEWED dev dependency: ${p.name}@${p.versions.join(',')} (${p.license})`);
      failed = true;
    }
  }

  const markdown = renderMarkdown(prod);
  if (mode === '--write') {
    writeFileSync(outFile, markdown);
    console.log(`Wrote ${outFile} (${prod.length} packages)`);
  } else if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== markdown) {
    console.error('THIRD_PARTY_LICENSES.md is outdated. Run `pnpm licenses:write`.');
    failed = true;
  }

  // The player must not gain runtime dependencies besides the format types.
  const playerPkg = JSON.parse(readFileSync(join(root, 'packages/player/package.json'), 'utf8'));
  const extra = Object.keys(playerPkg.dependencies ?? {}).filter((d) => d !== '@clipcourse/format');
  if (extra.length > 0) {
    console.error(`The player must not have runtime dependencies: ${extra.join(', ')}`);
    failed = true;
  }

  if (failed) process.exit(1);
  console.log(
    `License check passed: ${prod.length} production, ${dev.length} development packages.`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
